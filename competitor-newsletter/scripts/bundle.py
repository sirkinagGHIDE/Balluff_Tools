#!/usr/bin/env python3
"""Build data/digest.js from config/competitors.json, data/items/*.json and data/sample/*.json.

The page loads data/digest.js with a plain <script> tag (no fetch), so it works from
file:// and from GitHub Pages. Output is deterministic: the same inputs always give
byte-identical output, which lets validate.py (rule 9) compare it with a fresh build.

Usage:
    python scripts/bundle.py            # write data/digest.js
    python scripts/bundle.py --check    # exit 1 if data/digest.js is stale
    python scripts/bundle.py --root DIR # operate on another checkout or fixture
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
HEADER = (
    "// GENERATED by scripts/bundle.py. Do not edit by hand.\n"
    "// Rebuild with: python scripts/bundle.py\n"
)
COMPETITOR_FIELDS = ("id", "display_name", "parent_company", "ownership", "parent_reporting")


def config_dir(root: Path) -> Path:
    """Fixture roots may omit config/; fall back to the repo's own config."""
    own = root / "config"
    return own if (own / "competitors.json").is_file() else REPO_ROOT / "config"


def load_json(path: Path):
    with path.open(encoding="utf-8") as fh:
        return json.load(fh)


def load_runs(directory: Path) -> list[dict]:
    if not directory.is_dir():
        return []
    runs = [load_json(p) for p in sorted(directory.glob("*.json"))]
    runs.sort(key=lambda r: str(r.get("run_date", "")), reverse=True)
    return runs


def build(root: Path) -> dict:
    competitors = load_json(config_dir(root) / "competitors.json")["competitors"]
    return {
        "competitors": [{k: c.get(k) for k in COMPETITOR_FIELDS} for c in competitors],
        "runs": load_runs(root / "data" / "items"),
        "sample_runs": load_runs(root / "data" / "sample"),
    }


def render(root: Path) -> str:
    body = json.dumps(build(root), indent=1, ensure_ascii=False)
    return f"{HEADER}window.DIGEST = {body};\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", type=Path, default=REPO_ROOT)
    parser.add_argument("--check", action="store_true", help="compare instead of writing")
    args = parser.parse_args(argv)

    root = args.root.resolve()
    target = root / "data" / "digest.js"
    fresh = render(root)

    if args.check:
        current = target.read_text(encoding="utf-8").replace("\r\n", "\n") if target.is_file() else None
        if current != fresh:
            print(f"{target}: stale or missing. Run: python scripts/bundle.py", file=sys.stderr)
            return 1
        print(f"{target}: up to date")
        return 0

    target.parent.mkdir(parents=True, exist_ok=True)
    with target.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(fresh)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
